
-- Project 2: Mini Banking Management System
-- Database: Oracle Database 21c XE

-- Table 1: Bank Customers
CREATE TABLE bank_customers (
    customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR2(100) NOT NULL,
    mobile_number VARCHAR2(15) UNIQUE,
    customer_status VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP,

    CONSTRAINT chk_bank_customer_status
        CHECK (customer_status IN ('ACTIVE', 'BLOCKED'))
);

-- Table 2: Bank Accounts
CREATE TABLE bank_accounts (
    account_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR2(20) NOT NULL UNIQUE,
    customer_id NUMBER NOT NULL,
    account_type VARCHAR2(20) NOT NULL,
    balance NUMBER(15,2) DEFAULT 0 NOT NULL,
    account_status VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP,

    CONSTRAINT fk_bank_account_customer
        FOREIGN KEY (customer_id)
        REFERENCES bank_customers(customer_id),

    CONSTRAINT chk_bank_account_type
        CHECK (account_type IN ('SAVINGS', 'CURRENT')),

    CONSTRAINT chk_bank_account_balance
        CHECK (balance >= 0),

    CONSTRAINT chk_bank_account_status
        CHECK (account_status IN ('ACTIVE', 'BLOCKED', 'CLOSED'))
);

-- Table 3: Bank Transactions
CREATE TABLE bank_transactions (
    transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_reference VARCHAR2(30) NOT NULL UNIQUE,
    account_id NUMBER NOT NULL,
    transaction_type VARCHAR2(15) NOT NULL,
    transaction_amount NUMBER(15,2) NOT NULL,
    transaction_status VARCHAR2(10) DEFAULT 'SUCCESS' NOT NULL,
    description VARCHAR2(200),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP,

    CONSTRAINT fk_bank_transaction_account
        FOREIGN KEY (account_id)
        REFERENCES bank_accounts(account_id),

    CONSTRAINT chk_bank_transaction_type
        CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),

    CONSTRAINT chk_bank_transaction_amount
        CHECK (transaction_amount > 0),

    CONSTRAINT chk_bank_transaction_status
        CHECK (transaction_status IN ('SUCCESS', 'FAILED'))
);
